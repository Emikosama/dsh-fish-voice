import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname, join } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const require = createRequire(join(root, 'package.json'))
const buildRequire = process.env.DSH_SOURCE_ROOT
  ? createRequire(join(process.env.DSH_SOURCE_ROOT, 'package.json')) : createRequire(join(root, 'ui/package.json'))
const esbuildPath = (() => { try { return buildRequire.resolve('esbuild') } catch { return createRequire(buildRequire.resolve('vite/package.json')).resolve('esbuild') } })()
const { build } = await import(pathToFileURL(esbuildPath))
const zodPackage = require.resolve('zod/package.json')
const zod = JSON.parse(await readFile(zodPackage, 'utf8'))
const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
if (zod.version !== manifest.devDependencies.zod) throw new Error(`Expected zod ${manifest.devDependencies.zod}, found ${zod.version}`)

// Ship strict schemas and real Zod as local ESM. Desktop package resolution
// cannot depend on pnpm hoisting or plugin-local node_modules.
const result = await build({
  absWorkingDir: root,
  entryPoints: ['ui/src/conversation-contract.mjs'],
  outfile: 'ui/conversation-contract.mjs',
  bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
  minify: true, metafile: true, legalComments: 'none',
  banner: { js: `// Generated by ui/scripts/build-contract.mjs from ui/src/conversation-contract.mjs.\n// Includes Zod ${zod.version}; see conversation-contract.LICENSE. Do not edit directly.` },
})
for (const output of Object.values(result.metafile.outputs)) {
  if (output.imports.length) throw new Error('The shipped conversation contract must not have external imports')
}
await writeFile(join(root, 'ui/conversation-contract.LICENSE'), `Zod ${zod.version}\nhttps://github.com/colinhacks/zod\n\n${await readFile(join(dirname(zodPackage), 'LICENSE'), 'utf8')}`)
console.log(`Built self-contained conversation contract with Zod ${zod.version}`)
