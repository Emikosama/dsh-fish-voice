import { createRequire } from 'node:module'
import { join } from 'node:path'
import { readFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

const root = join(import.meta.dirname, '..')
const require = createRequire(join(root, 'package.json'))
const buildRequire = createRequire(join(process.env.DSH_SOURCE_ROOT || join(root, 'ui'), 'package.json'))
const esbuild = (() => {
  try { return buildRequire.resolve('esbuild') }
  catch { return createRequire(buildRequire.resolve('vite/package.json')).resolve('esbuild') }
})()
const { build } = await import(pathToFileURL(esbuild))
const [manifest, semver, license] = await Promise.all([
  readFile(join(root, 'package.json'), 'utf8').then(JSON.parse),
  readFile(require.resolve('semver/package.json'), 'utf8').then(JSON.parse),
  readFile(require.resolve('semver/LICENSE'), 'utf8'),
])
if (manifest.devDependencies.semver !== semver.version) throw new Error('The installed node-semver must match the pinned version')
const result = await build({
  absWorkingDir: root,
  stdin: {
    contents: `export { default as compare } from 'semver/functions/compare.js'
export { default as parse } from 'semver/functions/parse.js'
export { default as satisfies } from 'semver/functions/satisfies.js'
export { default as validRange } from 'semver/ranges/valid.js'`,
    resolveDir: root,
  },
  outfile: 'voice-update-semver.mjs',
  bundle: true, format: 'esm', platform: 'node', target: 'node24',
  minify: true, metafile: true, legalComments: 'none',
  banner: { js: `// Generated by scripts/build-update-semver.mjs from node-semver ${semver.version}.
// https://github.com/npm/node-semver
/*
${license.trimEnd()}
*/` },
})
if (Object.values(result.metafile.outputs).some(output => output.imports.length)) {
  throw new Error('The shipped version parser must not have external imports')
}
